// ФИНАЛЬНАЯ ЭКСПЕРТИЗА

function finalExamination() {
    const errors = [];

    // --- 1. Тип ---
    const typeOk = sessionAnswers.type === sessionAnswers.typeCorrect;

    // --- 2. Исполнитель ---
    const execOk = sessionAnswers.executor === sessionAnswers.executorCorrect;

    // --- 3. Карточки ---
    // Эталон: id правильных карточек из currentCards
    const expectedTasks = currentCards.filter(c => c.type === 'task' && c.correct).map(c => String(c.id));
    const expectedInd = currentCards.filter(c => c.type === 'indicator' && c.correct).map(c => String(c.id));
    const expectedMeas = currentCards.filter(c => c.type === 'measure' && c.correct).map(c => String(c.id));

    // Что игрок реально положил (по слотам)
    const placedTasks = sessionAnswers.cards.filter(c => c.placedInSlot === 'task').map(c => String(c.cardId));
    const placedInd = sessionAnswers.cards.filter(c => c.placedInSlot === 'indicator').map(c => String(c.cardId));
    const placedMeas = sessionAnswers.cards.filter(c => c.placedInSlot === 'measure').map(c => String(c.cardId));

    // Проверка по каждому слоту
    const checkSlot = (placed, expected, label) => {
        const missing = expected.filter(id => !placed.includes(id));
        const extra = placed.filter(id => !expected.includes(id));
        if (missing.length || extra.length) {
            errors.push({ label, missing, extra });
        }
    };
    checkSlot(placedTasks, expectedTasks, 'Задачи');
    checkSlot(placedInd, expectedInd, 'Показатели');
    checkSlot(placedMeas, expectedMeas, 'Мероприятия');

    // --- 4. Показываем экран разбора ---
    showResults({
        typeOk,
        execOk,
        errors,
        placedTasks, placedInd, placedMeas,
        expectedTasks, expectedInd, expectedMeas
    });
}

// ИТОГОВЫЙ ЭКРАН
function showResults(data) {
    document.getElementById('stepConstruct').style.display = 'none';
    document.getElementById('resultScreen').style.display = 'block';

    const content = document.getElementById('resultContent');
    let html = '';

    // ===== БЛОК 1. ТИП =====
    html += `
        <div class="review-block ${data.typeOk ? 'ok' : 'fail'}">
            <h4>${data.typeOk ? '✅' : '❌'} Тип структурного элемента</h4>
            <p><strong>Ваш ответ:</strong> ${sessionAnswers.type}</p>
            ${!data.typeOk ? `<p><strong>Правильно:</strong> ${sessionAnswers.typeCorrect}</p>` : ''}
            <p class="explain">💡 ${getTypeExplanation(sessionAnswers.typeCorrect)}</p>
        </div>
    `;

    // ===== БЛОК 2. ИСПОЛНИТЕЛЬ =====
    

    // ===== БЛОК 3. КАРТОЧКИ =====
    const slotNames = { task: 'Задачи', indicator: 'Показатели', measure: 'Мероприятия' };
    const expectedMap = {
        task: data.expectedTasks,
        indicator: data.expectedInd,
        measure: data.expectedMeas
    };
    const placedMap = {
        task: data.placedTasks,
        indicator: data.placedInd,
        measure: data.placedMeas
    };

    ['task', 'indicator', 'measure'].forEach(slot => {
        const expectedIds = expectedMap[slot];
        const placedIds = placedMap[slot];
        const missing = expectedIds.filter(id => !placedIds.includes(id));
        const extra = placedIds.filter(id => !expectedIds.includes(id));

        if (missing.length === 0 && extra.length === 0) {
            html += `<div class="review-block ok">
                <h4>✅ ${slotNames[slot]}</h4>
                <p>Все карточки собраны верно (${expectedIds.length} из ${expectedIds.length}).</p>
            </div>`;
            return;
        }

        html += `<div class="review-block fail">
            <h4>❌ ${slotNames[slot]}</h4>`;

        // Пропущенные правильные карточки
        if (missing.length) {
            html += `<p><strong>Не хватает:</strong></p><ul>`;
            missing.forEach(id => {
                const card = currentCards.find(c => String(c.id) === id);
                if (card) {
                    html += `<li>«${card.text}» — <span class="explain">${getCardExplanation(card, slot, true)}</span></li>`;
                }
            });
            html += `</ul>`;
        }

        // Лишние карточки
        if (extra.length) {
            html += `<p><strong>Лишние (не относятся к элементу):</strong></p><ul>`;
            extra.forEach(id => {
                const card = currentCards.find(c => String(c.id) === id);
                if (card) {
                    html += `<li>«${card.text}» — <span class="explain">${getCardExplanation(card, slot, false)}</span></li>`;
                }
            });
            html += `</ul>`;
        }

        html += `</div>`;
    });

    // ===== БЛОК 4. ИТОГОВАЯ СХЕМА (п. 4.2) =====
    html += renderFinalSchema();


    content.innerHTML = html;

    // Восстанавливаем обработчик
    document.getElementById('restartBtn').addEventListener('click', restartGame);
}

