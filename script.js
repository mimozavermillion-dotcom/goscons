// SMART-ВАЛИДАЦИЯ
function validateSMART() {
    const specific = document.getElementById('specific').value;
    const measurable = document.getElementById('measurable').value.trim();
    const okei = document.getElementById('okeiSelect').value;
    const budget = parseInt(document.getElementById('budget').value);
    const program = document.getElementById('programSelect').value;
    const decree = document.getElementById('decreeSelect').value;
    const time = document.getElementById('timebound').value;
    const federal = document.getElementById('federalLevel').value;

    let errors = [];
    if (!federal) errors.push("Выберите нацпроект или федпроект (R)");
    if (!specific) errors.push("Выберите конкретность (S)");
    if (specific === "разработка") errors.push("Ошибка: цель не должна быть 'разработка'. Используйте повышение/обеспечение/снижение.");
    if (!measurable) errors.push("Укажите числовое значение (M)");
    if (!okei) errors.push("Выберите единицу измерения по ОКЕИ (M)");
    if (isNaN(budget) || budget < 10) errors.push("Бюджет нереалистичен (A)");
    if (budget > 350) errors.push("Достижимость под вопросом: бюджет выше среднего на 75%+");
    if (!program) errors.push("Выберите госпрограмму (R)");
    if (!decree) errors.push("Выберите стратегический указ или 'нет связи' (R)");
    if (!time) errors.push("Выберите срок (T)");

    const msgDiv = document.getElementById('smartMessage');
    if (errors.length > 0) {
        msgDiv.innerHTML = `<span style="color:#b91c1c;">❌ SMART не пройден: ${errors.join('; ')}</span>`;
        return;
    }
    currentGoal = { specific, measurable, okei, budget, program, decree, federal, time };
    msgDiv.innerHTML = `<span style="color:#1f6d43;">✅ SMART-цель одобрена!</span>`;
    smartApproved = true;
    document.getElementById('gameBlock').style.display = 'block';
    document.getElementById('smartBlock').style.opacity = '0.7';
    loadElement();

}
