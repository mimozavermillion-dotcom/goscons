function normalizeDecree(decree) {
    if (!decree || decree === "нет") return "нет";
    
    // Ищем дату вида "08 апреля 2020" или "7 мая 2024"
    const dateMatch = decree.match(/(\d{1,2}\s+[а-яё]+\s+\d{4})/i);
    // Ищем номер вида "№ 1103", "№410", "№ 2", "№269"
    const numMatch = decree.match(/№\s*(\d+)/);
    
    if (dateMatch && numMatch) {
        return `${dateMatch[1].toLowerCase()} №${numMatch[1]}`;
    }
    // Если структура нестандартная — возвращаем строку как есть
    return decree.trim().toLowerCase();
}
function getTypeExplanation(correctType) {
    if (correctType === 'Региональный проект') {
        return 'Региональный проект входит в состав национального проекта и реализуется на уровне субъекта РФ. Его показатели должны совпадать с показателями федерального проекта.';
    }
    if (correctType === 'Ведомственный проект') {
        return 'Ведомственный проект реализуется одним органом власти в рамках его полномочий и не входит в состав национального проекта. У него свои задачи и показатели.';
    }
    if (correctType === 'Иной региональный проект') {
        return 'Иной региональный проект — это региональный проект особого типа, не относящийся к стандартным региональным проектам в составе нацпроектов.';
    }
    if (correctType === 'Комплекс процессных мероприятий') {
        return 'Комплекс процессных мероприятий — это система регулярных, повторяющихся мероприятий (не проект). У него нет уникального продукта, но есть показатели и мероприятия.';
    }
    return '';
}

