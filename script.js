function loadElement() {
    const program = currentGoal.program;
    const decree = currentGoal.decree;
    const federal = currentGoal.federal;
    const normDecree = normalizeDecree(decree); // <-- добавили
    const candidates = STRUCTURAL_ELEMENTS.filter(el => 
        el.program === program && 
        normalizeDecree(el.decree) === normDecree &&
        el.federalType === federal
    );
    if (candidates.length === 0) {
        document.getElementById('elementName').textContent = "Нет элементов для выбранных фильтров";
        document.getElementById('elementProgram').textContent = "—";
        document.getElementById('elementDecree').textContent = "—";
        document.getElementById('elementExecutor').textContent = "—";
        document.getElementById('typeFeedback').innerHTML = 
            `<span style="color:#b91c1c;">❌ Для выбранных фильтров нет структурных элементов. Попробуйте другие.</span>`;
        document.getElementById('nextToConstructBtn').style.display = 'none';
        document.getElementById('stepConstruct').style.display = 'none';
        return;
    }
    let selected;
    if (candidates.length === 1) {
        selected = candidates[0];
    } else {
        const randomIndex = Math.floor(Math.random() * candidates.length);
        selected = candidates[randomIndex];
    }

    currentElement = selected;
    typeSelected = false;
    selectedType = "";
    document.getElementById('nextToConstructBtn').style.display = 'none';
    document.getElementById('stepConstruct').style.display = 'none';
    document.getElementById('elementName').textContent = currentElement.name;
    document.getElementById('elementProgram').textContent = currentElement.program;
    document.getElementById('elementDecree').textContent = currentElement.decree === "нет" ? "нет связи" : currentElement.decree;
    document.getElementById('elementExecutor').textContent = currentElement.executor;
    document.getElementById('typeFeedback').innerHTML = '';
    document.getElementById('stepType').style.display = 'block';
    document.querySelectorAll('.type-btn').forEach(b => b.classList.remove('selected', 'correct', 'wrong'));
    if (candidates.length > 1) {
        document.getElementById('typeFeedback').innerHTML = 
            `<span style="color:#4a6a7a;">🔍 Найдено ${candidates.length} элементов. Для прохождения выбран случайный: <strong>«${currentElement.name}»</strong></span>`;
    }
}

