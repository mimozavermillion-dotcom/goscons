function getCardExplanation(card, slot, isMissing) {
    const slotName = slot === 'task' ? 'задач' : slot === 'indicator' ? 'показателей' : 'мероприятий';
    if (isMissing) {
        // Правильная карточка, которую игрок не поставил
        return `Эта карточка относится к разделу «${slotName}» элемента «${currentElement.name}» и указана в его паспорте.`;
    } else {
        // Лишняя карточка — объясняем, почему не подходит
        if (card.elementId) {
            return `Эта карточка относится к другому структурному элементу и не входит в паспорт «${currentElement.name}».`;
        }
        return `Этот текст не встречается в паспорте элемента «${currentElement.name}», поэтому карточка лишняя.`;
    }
}
