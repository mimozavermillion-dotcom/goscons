// ГЕНЕРАЦИЯ КАРТОЧЕК (правильные + дистракторы)
function generateCards() {
    if (!currentElement) return;
    cardIdCounter = 0;
    currentCards = [];

    // 1. Правильные карточки (из текущего элемента)
    // Задачи — нормализуем строку/объект
    currentElement.tasks.forEach(task => {
        const taskText = typeof task === 'string' ? task : task.name;
        currentCards.push({
            id: ++cardIdCounter,
            text: taskText,
            type: 'task',
            correct: true,
            elementId: currentElement.id
        });
    });

    // Показатели
    currentElement.indicators.forEach(ind => {
        currentCards.push({
            id: ++cardIdCounter,
            text: `${ind.name} (${ind.unit || 'ед.'})`,
            type: 'indicator',
            correct: true,
            elementId: currentElement.id
        });
    });

    // Мероприятия
    currentElement.measures.forEach(meas => {
        currentCards.push({
            id: ++cardIdCounter,
            text: `${meas.name} (${meas.unit || 'ед.'})`,
            type: 'measure',
            correct: true,
            elementId: currentElement.id
        });
    });

    // 2. Дистракторы (из других элементов)
    const otherElements = STRUCTURAL_ELEMENTS.filter(el => el.id !== currentElement.id);
    const distractors = [];
    otherElements.forEach(el => {
        el.tasks.forEach(t => {
            const tText = typeof t === 'string' ? t : t.name;
            distractors.push({ text: tText, type: 'task' });
        });
        el.indicators.forEach(ind => distractors.push({ text: `${ind.name} (${ind.unit || 'ед.'})`, type: 'indicator' }));
        el.measures.forEach(m => distractors.push({ text: `${m.name} (${m.unit || 'ед.'})`, type: 'measure' }));
    });

    const shuffled = distractors.sort(() => Math.random() - 0.5);
    const selectedDistractors = shuffled.slice(0, 8);

    selectedDistractors.forEach(d => {
        currentCards.push({
            id: ++cardIdCounter,
            text: d.text,
            type: d.type,
            correct: false,
            elementId: null
        });
    });

    currentCards.sort(() => Math.random() - 0.5);
}


// ОТРИСОВКА КАРТОЧЕК
function renderCards() {
    const container = document.getElementById('cardsContainer');
    container.innerHTML = '';

    currentCards.forEach(card => {
        const div = document.createElement('div');
        div.className = 'card';
        div.setAttribute('draggable', 'true');
        div.setAttribute('data-card-id', card.id);
        div.setAttribute('data-card-type', card.type);
        div.setAttribute('data-card-text', card.text);
        div.setAttribute('data-correct', card.correct ? 'true' : 'false');
        div.setAttribute('data-element-id', card.elementId || '');

        let typeLabel = '';
        if (card.type === 'task') typeLabel = '';
        else if (card.type === 'indicator') typeLabel = '';
        else if (card.type === 'measure') typeLabel = '';

        div.innerHTML = `${typeLabel} ${card.text}`;
        if (!card.correct) {
            div.style.opacity = '0.8';
            div.style.borderColor = '#e0a0a0';
        }

        div.addEventListener('dragstart', function(e) {
            e.dataTransfer.setData('text/plain', JSON.stringify({
                id: card.id,
                type: card.type,
                text: card.text,
                correct: card.correct,
                elementId: card.elementId
            }));
            e.dataTransfer.effectAllowed = 'copy';
            this.classList.add('dragging');
        });
        div.addEventListener('dragend', function(e) {
            this.classList.remove('dragging');
        });
        container.appendChild(div);
    });
}

// НАСТРОЙКА DROP
function setupDropTargets() {
    const slots = [
        document.getElementById('slotTasks'),
        document.getElementById('slotIndicators'),
        document.getElementById('slotMeasures')
    ];

    slots.forEach(slot => {
        slot.addEventListener('dragover', function(e) {
            e.preventDefault();
            e.dataTransfer.dropEffect = 'copy';
            this.classList.add('drag-over');
        });
        slot.addEventListener('dragleave', function() {
            this.classList.remove('drag-over');
        });
        slot.addEventListener('drop', function(e) {
    e.preventDefault();
    this.classList.remove('drag-over');

    const raw = e.dataTransfer.getData('text/plain');
    if (!raw) return;
    let cardInfo;
    try { cardInfo = JSON.parse(raw); } catch(e) { return; }

    const slotType = this.dataset.slotType;
    const cardType = cardInfo.type;

    // 1. Проверка ТИПА слота — оставляем. Нельзя задачу положить в показатели.
    //    Это не «ответ», это правило интерфейса.
    let typeMatch = false;
    if (slotType === 'task' && cardType === 'task') typeMatch = true;
    if (slotType === 'indicator' && cardType === 'indicator') typeMatch = true;
    if (slotType === 'measure' && cardType === 'measure') typeMatch = true;

    if (!typeMatch) {
        document.getElementById('constructFeedback').innerHTML =
            `<span class="error-feedback">❌ Сюда можно класть только карточки другого типа.</span>`;
        return;
    }

    // 2. Запрет дублей — одну карточку нельзя положить дважды
    if (this.querySelector(`.slot-item[data-card-id="${cardInfo.id}"]`)) {
        return;
    }

    // 3. ПРИНИМАЕМ ЛЮБУЮ КАРТОЧКУ — и верную, и лишнюю
    const item = document.createElement('div');
    item.className = 'slot-item';
    item.dataset.cardId = cardInfo.id;
    item.dataset.correct = cardInfo.correct ? 'true' : 'false'; // храним, но НЕ показываем
    item.textContent = cardInfo.text;
    this.appendChild(item);

    // 4. Запоминаем в сессии
    sessionAnswers.cards.push({
        cardId: cardInfo.id,
        text: cardInfo.text,
        type: cardType,
        correct: cardInfo.correct,
        placedInSlot: slotType
    });

    // 5. Убираем карточку из колоды (чтобы нельзя было перетащить повторно)
    const cardEl = document.querySelector(`.card[data-card-id="${cardInfo.id}"]`);
    if (cardEl) cardEl.remove();

    // 6. Нейтральная обратная связь
    document.getElementById('constructFeedback').innerHTML =
        `<span style="color:#4a6a7a;">📌 Карточка добавлена: «${cardInfo.text}». Проверка будет в конце.</span>`;
});
    });
}

